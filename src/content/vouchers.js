/** Цената на масаж с дадена продължителност, по ценовата листа. */
export function priceFor(name, minutes) {
  const m = massages.find((x) => x.name === name);
  const v = m?.variants.find(([min]) => min === minutes);
  return v ? v[1] : null;
}
